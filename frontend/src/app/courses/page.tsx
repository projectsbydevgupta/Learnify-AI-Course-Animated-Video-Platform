"use client";

import { useEffect, useState } from "react";
import Link from "next/link";

interface GeneratedCourse {
  id: string;
  title: string;
  description: string;
  difficulty: string;
  created_at: string | null;
  chapters_count: number;
  total_lessons: number;
  completed_lessons: number;
  failed_lessons: number;
  progress_percent: number;
}

export default function CoursesListPage() {
  const [courses, setCourses] = useState<GeneratedCourse[]>([]);
  const [loading, setLoading] = useState(true);

  const fetchCourses = async () => {
    try {
      const backendUrl = process.env.NEXT_PUBLIC_BACKEND_URL || "http://localhost:8000";
      const res = await fetch(`${backendUrl}/api/courses`);
      if (res.ok) {
        const data = await res.json();
        setCourses(data);
      }
    } catch (e) {
      console.error(e);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchCourses();
  }, []);

  return (
    <div className="min-h-screen bg-[#070b14] text-slate-100 p-4 sm:p-8 font-sans">
      <div className="max-w-6xl mx-auto space-y-8">
        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <Link
              href="/dashboard"
              className="inline-flex items-center gap-1.5 text-xs text-indigo-400 hover:text-indigo-300 font-semibold mb-2 transition group"
            >
              <span className="group-hover:-translate-x-1 transition-transform">←</span> Back to Dashboard
            </Link>
            <h1 className="text-3xl font-extrabold text-white flex items-center gap-3">
              <span>🎓</span> Generated Courses Library
            </h1>
            <p className="text-sm text-slate-400 mt-1">
              Multi-chapter educational curriculums generated by the autonomous agentic pipeline.
            </p>
          </div>

          <Link
            href="/dashboard/generate-course"
            className="px-5 py-3 bg-indigo-600 hover:bg-indigo-500 text-white rounded-xl text-xs font-bold transition shadow-lg shadow-indigo-950/50 flex items-center gap-2 self-start sm:self-auto"
          >
            <span>✨</span> Generate New Course
          </Link>
        </div>

        {/* Content */}
        {loading ? (
          <div className="p-12 text-center text-slate-400">Loading courses...</div>
        ) : courses.length === 0 ? (
          <div className="p-12 text-center rounded-3xl bg-slate-900/40 border border-slate-800 space-y-4">
            <span className="text-4xl">🎓</span>
            <h3 className="text-lg font-bold text-white">No Courses Generated Yet</h3>
            <p className="text-sm text-slate-400 max-w-md mx-auto">
              Create your first full multi-chapter course curriculum with automated videos and quizzes!
            </p>
            <Link
              href="/dashboard/generate-course"
              className="inline-block px-5 py-2.5 bg-indigo-600 hover:bg-indigo-500 rounded-xl text-xs font-bold text-white transition"
            >
              Start Course Generator →
            </Link>
          </div>
        ) : (
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
            {courses.map((course) => (
              <div
                key={course.id}
                className="p-6 rounded-2xl bg-slate-900/60 border border-slate-800 hover:border-indigo-500/40 transition-all duration-300 shadow-xl flex flex-col justify-between space-y-4 group"
              >
                <div className="space-y-3">
                  <div className="flex justify-between items-center text-xs">
                    <span className="px-2.5 py-0.5 rounded-full bg-indigo-500/10 text-indigo-300 border border-indigo-500/30 font-semibold uppercase tracking-wider">
                      🎓 Course Curriculum
                    </span>
                    <span className="font-mono text-slate-500">
                      {course.chapters_count} Chapters • {course.total_lessons} Lessons
                    </span>
                  </div>

                  <h3 className="text-lg font-bold text-white group-hover:text-indigo-300 transition-colors line-clamp-2">
                    {course.title}
                  </h3>

                  {course.description && (
                    <p className="text-xs text-slate-400 line-clamp-2 leading-relaxed">
                      {course.description}
                    </p>
                  )}

                  {/* Progress bar */}
                  <div className="space-y-1.5 pt-2">
                    <div className="flex justify-between text-xs text-slate-400">
                      <span>Progress</span>
                      <span className="font-mono font-bold text-emerald-400">
                        {course.completed_lessons} / {course.total_lessons} ({course.progress_percent}%)
                      </span>
                    </div>
                    <div className="w-full bg-slate-800 rounded-full h-2 overflow-hidden">
                      <div
                        className="bg-gradient-to-r from-indigo-500 to-emerald-500 h-full transition-all duration-500"
                        style={{ width: `${course.progress_percent}%` }}
                      />
                    </div>
                  </div>
                </div>

                <div className="pt-4 border-t border-slate-800/80">
                  <Link
                    href={`/courses/${course.id}`}
                    className="w-full inline-flex items-center justify-center py-2.5 px-4 bg-slate-800 hover:bg-indigo-600 text-slate-200 hover:text-white rounded-xl text-xs font-bold transition duration-200 shadow"
                  >
                    View Course Syllabus →
                  </Link>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}

